"""AI-assisted resume screener (phase 2).

Candidates sign up, upload a resume, apply for a role, get a keyword-match
score, and answer interview questions generated by an OpenAI model.

    streamlit run phase-2-extended-ai-version/app/app.py
"""

import os
import sys
from pathlib import Path

import nltk
import plotly.graph_objects as go
import streamlit as st
from dotenv import load_dotenv
from openai import OpenAI
from PIL import Image

APP_DIR = Path(__file__).resolve().parent
BASE_DIR = APP_DIR.parent
sys.path.insert(0, str(APP_DIR))

import auth  # noqa: E402
from text_utils import calculate_score, clean_for_prompt, extract_text, process_text  # noqa: E402

load_dotenv()

JOBS_DIR = BASE_DIR / "data" / "JobDesc"
LOGO = BASE_DIR / "Images" / "logo.png"
OPENAI_MODEL = os.environ.get("OPENAI_MODEL", "gpt-4o-mini")

session_state = st.session_state


@st.cache_resource
def ensure_nltk_data() -> None:
    for resource, path in (("punkt_tab", "tokenizers/punkt_tab"), ("stopwords", "corpora/stopwords")):
        try:
            nltk.data.find(path)
        except LookupError:
            nltk.download(resource, quiet=True)


@st.cache_data
def load_jobs() -> dict[str, str]:
    """Map role name -> job description text, one .docx per role in data/JobDesc."""
    return {path.stem: extract_text(str(path)) for path in sorted(JOBS_DIR.glob("*.docx"))}


@st.cache_resource
def get_client() -> OpenAI | None:
    return OpenAI() if os.environ.get("OPENAI_API_KEY") else None


def chat(messages: list[dict]) -> str:
    client = get_client()
    if client is None:
        st.error("OPENAI_API_KEY is not set. Add it to a .env file next to the app (see .env.example).")
        st.stop()
    response = client.chat.completions.create(model=OPENAI_MODEL, messages=messages)
    return response.choices[0].message.content


def extract_keywords_from_resume(resume_text: str) -> list[str]:
    prompt = (
        "Extract the most important skill keywords from this resume as a comma-separated list.\n\n"
        f"{clean_for_prompt(resume_text)}\n\nKeywords:"
    )
    return [k.strip() for k in chat([{"role": "user", "content": prompt}]).split(",") if k.strip()]


def generate_question(resume_text, job_description_text, candidate_name, previous_response=None, previous_question=None):
    prompt = f"Resume Text: {resume_text}\nJob Description: {job_description_text}\nCandidate Name: {candidate_name}\n"
    if previous_response and previous_question:
        prompt += f"Previous Question: {previous_question}\nPrevious Response: {previous_response}\n"
    return chat(
        [
            {
                "role": "system",
                "content": "You are interviewing a candidate. Ask one question based on the resume and job "
                "description. If the candidate has already answered a question, you may ask a follow-up.",
            },
            {"role": "user", "content": prompt},
        ]
    )


def save_user(updates: dict) -> None:
    user = auth.update_user(session_state["user_info"]["email"], updates)
    if user is None:
        st.error("User not found.")
    else:
        session_state["user_info"] = user


def require_login() -> bool:
    if not session_state.get("logged_in"):
        st.warning("Please login/signup to view the dashboard.")
        return False
    return True


def render_dashboard(user_info: dict) -> None:
    st.title(f"Welcome to the Dashboard, {user_info['name']}!")
    st.subheader("User Information:")
    st.write(f"Name: {user_info['name']}")
    st.write(f"Sex: {user_info['sex']}")
    st.write(f"Age: {user_info['age']}")


def signup_page() -> None:
    st.title("Signup Page")
    with st.form("signup_form"):
        st.write("Fill in the details below to create an account:")
        name = st.text_input("Name:")
        email = st.text_input("Email:")
        age = st.number_input("Age:", min_value=0, max_value=120)
        sex = st.radio("Sex:", ("Male", "Female", "Other"))
        password = st.text_input("Password:", type="password")
        confirm_password = st.text_input("Confirm Password:", type="password")
        if st.form_submit_button("Signup"):
            if password != confirm_password:
                st.error("Passwords do not match. Please try again.")
                return
            try:
                user = auth.create_user(name, email, int(age), sex, password)
            except ValueError as exc:
                st.error(str(exc))
                return
            session_state["logged_in"] = True
            session_state["user_info"] = user
            st.success("Account created successfully!")


def login_page() -> None:
    st.title("Login Page")
    email = st.text_input("Email:")
    password = st.text_input("Password:", type="password")
    if st.button("Login"):
        user = auth.authenticate(email, password)
        if user is None:
            st.error("Invalid credentials. Please try again.")
            return
        session_state["logged_in"] = True
        session_state["user_info"] = user
        st.success("Login successful!")
        render_dashboard(user)


def upload_page() -> None:
    uploaded_file = st.file_uploader("Choose a resume (.pdf, .docx or .txt)", type=["pdf", "docx", "txt"])
    if uploaded_file is not None:
        save_user({"resume": extract_text(uploaded_file)})
        st.write("File name: ", uploaded_file.name)
        st.success("File uploaded successfully!")
        st.image(Image.open(LOGO), width="stretch")

    st.subheader("Select a role you want to apply for:")
    jobs = load_jobs()
    role = st.selectbox("Select a role", ["-Select-", *sorted(jobs)], key="job_description")
    if role != "-Select-":
        st.subheader("Job Description:")
        st.write(jobs[role])
        if st.button("Apply"):
            save_user({"job_description": jobs[role], "job_applied": role})
            st.success("Job application submitted successfully!")


def analysis_page() -> None:
    user = session_state["user_info"]
    st.title("Get Your Resume Analyzed and Compared")
    if not user.get("resume") or not user.get("job_description"):
        st.warning("Upload your resume and apply for a role first.")
        return

    st.subheader("Skills of the candidate:")
    for keyword in extract_keywords_from_resume(user["resume"]):
        st.write(f"- {keyword}")

    score = calculate_score(process_text(user["job_description"]), process_text(user["resume"]))
    save_user({"score": score})

    st.header("Resume Score")
    if score >= 60:
        st.success(f"Congratulations! Your resume matches {score}% with the job description.")
    elif score >= 20:
        st.warning(f"Your resume matches {score}% with the job description. Consider improving it for better results.")
    else:
        st.error(f"Your resume matches only {score}% with the job description. Consider significant improvements.")

    fig = go.Figure(
        data=[
            go.Pie(
                labels=["Matched", "Unmatched"],
                values=[score, 100 - score],
                hole=0.3,
                marker_colors=["rgba(0, 128, 0, 0.7)", "rgba(255, 0, 0, 0.7)"],
            )
        ]
    )
    fig.update_layout(title_text="Resume Score")
    st.plotly_chart(fig)

    st.subheader("How does your resume compare with other candidates?")
    role = user["job_applied"]
    scores = [float(u["score"]) for u in auth.load_db()["users"] if u.get("job_applied") == role]
    hist = go.Figure(go.Histogram(x=scores, histnorm="percent", marker_color="rgba(0, 0, 255, 0.7)", opacity=0.75))
    hist.update_layout(
        title_text=f"Distribution of Scores for Job Role: {role}",
        xaxis_title="Resume Score",
        yaxis_title="Percentage of Candidates",
        bargap=0.05,
    )
    st.plotly_chart(hist)


def questions_page() -> None:
    user = session_state["user_info"]
    st.title("Interview Question Generator Chat")
    if not user.get("resume") or not user.get("job_description"):
        st.warning("Please upload your resume and apply for a job to generate interview questions.")
        return

    history = user.get("questions") or []
    # Generate one question per turn and keep it across reruns, so typing an
    # answer does not trigger a new (billed) API call.
    if "current_question" not in session_state:
        last = history[-1] if history else {}
        session_state["current_question"] = generate_question(
            user["resume"], user["job_description"], user["name"], last.get("response"), last.get("question")
        )
    question = session_state["current_question"]

    st.markdown("### Interview Question")
    st.markdown(question)
    response = st.text_input("Your response:")

    col_next, col_finish = st.columns(2)
    if col_next.button("Next Question") and response:
        save_user({"questions": [*history, {"question": question, "response": response}]})
        del session_state["current_question"]
        st.rerun()
    if col_finish.button("Finish"):
        if response:
            save_user({"questions": [*history, {"question": question, "response": response}]})
        session_state.pop("current_question", None)
        st.success("Interview questions completed successfully!")


def scores_page() -> None:
    user = session_state["user_info"]
    st.title("Evaluate Scores")
    questions = user.get("questions") or []
    if not questions:
        st.info("Answer some interview questions first.")
        return
    st.markdown("### Interview Questions and Responses")
    for item in questions:
        st.markdown(f"**Question:** {item['question']}")
        st.markdown(f"**Response:** {item['response']}")
        st.markdown("---")
    # Keyword overlap between each question and its answer, averaged.
    score = sum(calculate_score(process_text(q["question"]), process_text(q["response"])) for q in questions)
    st.subheader("Score")
    st.write(f"Score: {round(score / len(questions), 2)} %")


def main() -> None:
    ensure_nltk_data()
    auth.initialize_database()

    st.sidebar.title("Resume Screening system")
    page = st.sidebar.radio(
        "Go to",
        ("Signup/Login", "Upload Resume", "Resume Analysis", "Generate Questions", "Evaluate Scores"),
    )

    if page == "Signup/Login":
        st.title("Signup/Login Page")
        if st.radio("Select an option", ("Login", "Signup"), key="login_signup") == "Login":
            login_page()
        else:
            signup_page()
    elif require_login():
        {
            "Upload Resume": upload_page,
            "Resume Analysis": analysis_page,
            "Generate Questions": questions_page,
            "Evaluate Scores": scores_page,
        }[page]()


if __name__ == "__main__":
    main()
